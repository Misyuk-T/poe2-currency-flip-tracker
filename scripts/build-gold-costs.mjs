#!/usr/bin/env node
/**
 * Refetch PoE2 Currency Exchange gold costs from poe2db.tw and rewrite
 * src/data/gold-costs-poe2.js.
 *
 * GGG publishes no gold-cost formula anywhere (verified: the official
 * Currency Exchange CDN response has no gold/tax/fee field) — it's a curated
 * per-item table, same as poe2db.tw's page. Each scraped entry carries its
 * GGG Metadata id and is matched by EXACT display name against
 * src/data/catalog-poe2.json's trade short ids. Unmatched items (rare
 * uniques/idols/omens not in the trade-catalog snapshot) are omitted, never
 * guessed — see the honesty rule in the generated file's header.
 *
 * Network-gated; run manually or via the scheduled data-refresh workflow:
 *   node scripts/build-gold-costs.mjs
 *
 * Attribution: gold-cost data derived from https://poe2db.tw (fan wiki, not
 * affiliated with GGG). PoE item names/data © Grinding Gear Games.
 */

import { writeFile, rename, unlink } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const SOURCE_URL = "https://poe2db.tw/us/Currency_Exchange";
const UA = process.env.USER_AGENT ?? "poe2-currency-flip-tracker/0.1 (gold-cost build; non-commercial)";
const OUT_PATH = fileURLToPath(new URL("../src/data/gold-costs-poe2.js", import.meta.url));
const CATALOG_PATH = fileURLToPath(new URL("../src/data/catalog-poe2.json", import.meta.url));

// Sanity floors — guard against a truncated/changed page silently shrinking coverage.
const MIN_MATCHED = 500;
const REQUIRED_IDS = ["exalted", "divine", "chaos"];

// `data-hover="?s=Data%5CBaseItemTypes%2FMetadata%2FItems%2F...">Name</a><span>123</span>` —
// the second (text) <a> for each item is immediately followed by its gold <span>;
// the first (image) <a> is followed by an <img>, so this pattern only matches once per item.
const ITEM_RE = /data-hover="\?s=([^"]+)"\s+href="[^"]*">([^<]+)<\/a><span>(\d+)<\/span>/g;

function nameKey(name) {
  return name.trim().toLowerCase();
}

function jsString(value) {
  return JSON.stringify(value);
}

async function main() {
  console.log(`Fetching ${SOURCE_URL} ...`);
  const res = await fetch(SOURCE_URL, {
    headers: { "User-Agent": UA, Accept: "text/html" },
    signal: AbortSignal.timeout(15_000),
  });
  if (!res.ok) throw new Error(`poe2db.tw returned ${res.status}`);
  const html = await res.text();

  const scraped = [];
  const seen = new Set();
  for (const match of html.matchAll(ITEM_RE)) {
    const [, rawHover, rawName, rawGold] = match;
    const decoded = decodeURIComponent(rawHover);
    const metaIdx = decoded.indexOf("Metadata/");
    const metadataPath = metaIdx === -1 ? null : decoded.slice(metaIdx);
    const name = rawName
      .replace(/&#(\d+);/g, (_, code) => String.fromCharCode(Number(code)))
      .replace(/&amp;/g, "&")
      .trim();
    const goldPerUnit = Number(rawGold);
    const key = `${metadataPath}|${name}|${goldPerUnit}`;
    if (seen.has(key)) continue;
    seen.add(key);
    scraped.push({ metadataPath, name, goldPerUnit });
  }
  console.log(`Parsed ${scraped.length} scraped items.`);

  const { default: catalog } = await import(CATALOG_PATH, { with: { type: "json" } });
  const nameToId = new Map();
  for (const item of catalog.items ?? []) {
    const key = nameKey(item.name);
    if (!nameToId.has(key)) nameToId.set(key, [item.id]);
    else nameToId.get(key).push(item.id);
  }

  const matched = [];
  const unmatched = [];
  for (const item of scraped) {
    const ids = nameToId.get(nameKey(item.name));
    if (ids && ids.length === 1) matched.push([ids[0], item.name, item.goldPerUnit]);
    else unmatched.push(item.name);
  }
  matched.sort((a, b) => a[0].localeCompare(b[0]));

  if (matched.length < MIN_MATCHED) {
    throw new Error(`only ${matched.length} matched items (< ${MIN_MATCHED}); refusing to overwrite`);
  }
  const matchedIds = new Set(matched.map((row) => row[0]));
  for (const id of REQUIRED_IDS) {
    if (!matchedIds.has(id)) throw new Error(`required id "${id}" missing from the match; refusing to overwrite`);
  }

  const fetchedAt = new Date().toISOString().slice(0, 10);
  const tableBody = matched.map(([id, name, gold]) => `  [${jsString(id)}, ${jsString(name)}, ${gold}],`).join("\n");

  const out = `/**
 * Versioned PoE2 gold-cost registry.
 *
 * Gold is a second scarce, account-bound resource. Every currency-exchange leg
 * costs gold proportional to the quantity *received*:
 *
 *     gold_for_leg = ceil(received_quantity * goldPerUnit)
 *
 * These values are a data-derived snapshot, NOT an eternal universal formula —
 * GGG publishes no formula anywhere (verified: the official Currency Exchange
 * CDN response has no gold/tax/fee field at all). They must stay
 * verifiable/configurable and must NEVER be silently shared with PoE1 (which
 * uses a different table).
 *
 * GENERATED by scripts/build-gold-costs.mjs — do not hand-edit; re-run the
 * script instead. Source: ${SOURCE_URL} (fetched ${fetchedAt}), matched by
 * exact display name against src/data/catalog-poe2.json's trade short ids.
 * ${matched.length} matched, ${unmatched.length} omitted (no confident
 * catalog match — never guessed, per the honesty rule below).
 *
 * Maintenance: re-run \`node scripts/build-gold-costs.mjs\` (or let the
 * scheduled data-refresh workflow open a PR). To hand-add a one-off value,
 * add a row directly to {@link GOLD_TABLE} — it will be overwritten on the
 * next generated run, so prefer fixing the source/match logic instead.
 *
 * Honesty rule: do NOT invent a gold cost for a currency you cannot source. A
 * missing entry is surfaced as a coverage gap and the target is marked
 * unrankable; it is never guessed.
 *
 * @typedef {Object} GoldCostRecord
 * @property {"poe2"} game
 * @property {string} patchOrVersion
 * @property {string} itemId       Stable exchange item id (matches GGG \`have\`/\`want\` ids).
 * @property {string} displayName
 * @property {number} goldPerUnit  Gold cost per received unit (integer).
 * @property {string} effectiveFrom ISO date this value was observed/applies from.
 * @property {string} source
 */

const PROVENANCE = {
  game: /** @type {"poe2"} */ ("poe2"),
  patchOrVersion: "0.3-observed-${fetchedAt}",
  effectiveFrom: "${fetchedAt}",
  source: "poe2db.tw/us/Currency_Exchange scrape, matched against catalog-poe2.json by name",
};

/** @type {[string, string, number][]} \`[itemId, displayName, goldPerUnit]\` */
const GOLD_TABLE = [
${tableBody}
];

function buildRecords(table, provenance) {
  return table.map(([itemId, displayName, goldPerUnit]) => ({
    ...provenance,
    itemId,
    displayName,
    goldPerUnit,
  }));
}

/** @type {GoldCostRecord[]} */
export const POE2_GOLD_COSTS = buildRecords(GOLD_TABLE, PROVENANCE);
`;

  const tmp = `${OUT_PATH}.tmp-${process.pid}`;
  try {
    await writeFile(tmp, out);
    await rename(tmp, OUT_PATH);
  } catch (err) {
    await unlink(tmp).catch(() => {});
    throw err;
  }
  console.log(`Wrote ${matched.length} gold-cost items -> ${OUT_PATH}`);
  if (unmatched.length) {
    console.log(`Unmatched (omitted, not guessed): ${unmatched.slice(0, 20).join(", ")}${unmatched.length > 20 ? ", ..." : ""}`);
  }
}

main().catch((err) => {
  console.error("build-gold-costs failed:", err.message);
  process.exit(1);
});
